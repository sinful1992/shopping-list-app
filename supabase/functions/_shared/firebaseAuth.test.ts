const PROJECT = 'test-project';
const DB_URL = 'https://db.example';
const saKeys = generateKeyPairSync('rsa', { modulusLength: 2048 });
const SERVICE_ACCOUNT = {
  project_id: PROJECT,
  client_email: 'svc@test-project.iam.gserviceaccount.com',
  private_key: saKeys.privateKey.export({ type: 'pkcs8', format: 'pem' }) as string,
};
const signer = generateKeyPairSync('rsa', { modulusLength: 2048 });
const KID = 'kid-1';
const jwk = { ...(signer.publicKey.export({ format: 'jwk' }) as object), kid: KID, alg: 'RS256', use: 'sig' };

const b64url = (s: string | Buffer) => Buffer.from(s).toString('base64url');
function idToken(over: Record<string, unknown> = {}, key = signer.privateKey, kid = KID): string {
  const now = Math.floor(Date.now() / 1000);
  const head = b64url(JSON.stringify({ alg: 'RS256', kid }));
  const body = b64url(JSON.stringify({
    aud: PROJECT, iss: `https://securetoken.google.com/${PROJECT}`, sub: 'user-1', iat: now - 10, exp: now + 3000, ...over,
  }));
  const sig = createSign('RSA-SHA256').update(`${head}.${body}`).sign(key);
  return `${head}.${body}.${b64url(sig)}`;
}

let mints = 0;
let jwkFetches = 0;
let oauthReply: () => object = () => ({ access_token: `tok-${++mints}`, expires_in: 3600 });
let dbReply: (url: string) => { status: number; body: unknown } = () => ({ status: 200, body: true });
const seenTokens: string[] = [];

function installFetch() {
  (globalThis as any).fetch = jest.fn(async (url: string) => {
    if (url.startsWith('https://oauth2.googleapis.com/token')) {
      await new Promise(r => setTimeout(r, 5));
      return { ok: true, status: 200, json: async () => oauthReply() };
    }
    if (url.includes('securetoken@system.gserviceaccount.com')) {
      jwkFetches++;
      return { ok: true, status: 200, json: async () => ({ keys: [jwk] }) };
    }
    if (url.startsWith(DB_URL)) {
      seenTokens.push(new URL(url).searchParams.get('access_token') ?? '');
      const r = dbReply(url);
      return { ok: r.status < 300, status: r.status, json: async () => r.body };
    }
    throw new Error(`unexpected fetch ${url}`);
  });
}

let auth: any;
let nowMs = Date.UTC(2026, 10, 11, 18, 0, 0);

beforeEach(() => {
  jest.resetModules();
  mints = 0;
  jwkFetches = 0;
  seenTokens.length = 0;
  oauthReply = () => ({ access_token: `tok-${++mints}`, expires_in: 3600 });
  dbReply = () => ({ status: 200, body: true });
  nowMs = Date.UTC(2026, 10, 11, 18, 0, 0);
  jest.spyOn(Date, 'now').mockImplementation(() => nowMs);
  (globalThis as any).Deno = {
    env: { get: (n: string) => ({ FIREBASE_SERVICE_ACCOUNT: JSON.stringify(SERVICE_ACCOUNT), FIREBASE_DATABASE_URL: DB_URL } as Record<string, string>)[n] },
  };
  installFetch();
  auth = existsSync(shared) ? require('./firebaseAuth') : {};
});

afterEach(() => {
  jest.restoreAllMocks();
});

describe('database token reuse', () => {
  it('three membership checks mint one token', async () => {
    for (let i = 0; i < 3; i++) await auth.assertGroupMember('user-1', 'fam-1');
    expect(mints).toBe(1);
    expect(seenTokens).toEqual(['tok-1', 'tok-1', 'tok-1']);
  });

  it('checks arriving together share one mint', async () => {
    await Promise.all(Array.from({ length: 5 }, () => auth.assertGroupMember('user-1', 'fam-1')));
    expect(mints).toBe(1);
  });

  it('a token with under 5 minutes left is replaced', async () => {
    await auth.assertGroupMember('user-1', 'fam-1');
    nowMs += (3600 - 299) * 1000;
    await auth.assertGroupMember('user-1', 'fam-1');
    expect(mints).toBe(2);
    expect(seenTokens).toEqual(['tok-1', 'tok-2']);
  });

  it('a token with more than 5 minutes left is kept', async () => {
    await auth.assertGroupMember('user-1', 'fam-1');
    nowMs += (3600 - 301) * 1000;
    await auth.assertGroupMember('user-1', 'fam-1');
    expect(mints).toBe(1);
  });

  it('a failed mint is not cached: the next request tries again', async () => {
    oauthReply = () => ({ error: 'invalid_grant' });
    await expect(auth.assertGroupMember('user-1', 'fam-1')).rejects.toThrow('Failed to get Firebase access token');
    oauthReply = () => ({ access_token: `tok-${++mints}`, expires_in: 3600 });
    await auth.assertGroupMember('user-1', 'fam-1');
    expect(seenTokens).toEqual(['tok-1']);
  });

  it('a token the database rejects (401) is dropped, so the next request mints a new one', async () => {
    dbReply = () => ({ status: 401, body: { error: 'Unauthorized' } });
    await expect(auth.assertGroupMember('user-1', 'fam-1')).rejects.toThrow('Membership check failed');
    dbReply = () => ({ status: 200, body: true });
    await auth.assertGroupMember('user-1', 'fam-1');
    expect(seenTokens).toEqual(['tok-1', 'tok-2']);
  });

  it('a short expires_in from Google is honoured', async () => {
    oauthReply = () => ({ access_token: `tok-${++mints}`, expires_in: 600 });
    await auth.assertGroupMember('user-1', 'fam-1');
    nowMs += 301 * 1000;
    await auth.assertGroupMember('user-1', 'fam-1');
    expect(mints).toBe(2);
  });

  it('not a member, or no family id: refused', async () => {
    dbReply = () => ({ status: 200, body: null });
    await expect(auth.assertGroupMember('user-1', 'fam-1')).rejects.toThrow('not a member');
    await expect(auth.assertGroupMember('user-1', '')).rejects.toThrow('Missing family group ID');
    await expect(auth.assertGroupMember('user-1', 42)).rejects.toThrow('Missing family group ID');
  });

  it('the minted JWT is signed by the service account key', async () => {
    let assertion = '';
    (globalThis as any).fetch = jest.fn(async (url: string, init?: { body?: string }) => {
      if (url.startsWith('https://oauth2.googleapis.com/token')) {
        assertion = new URLSearchParams(init?.body ?? '').get('assertion') ?? '';
        return { ok: true, status: 200, json: async () => ({ access_token: 't', expires_in: 3600 }) };
      }
      return { ok: true, status: 200, json: async () => true };
    });
    await auth.assertGroupMember('user-1', 'fam-1');
    const [h, c, s] = assertion.split('.');
    const ok = await webcrypto.subtle.verify(
      'RSASSA-PKCS1-v1_5',
      await webcrypto.subtle.importKey('spki', saKeys.publicKey.export({ type: 'spki', format: 'der' }), { name: 'RSASSA-PKCS1-v1_5', hash: 'SHA-256' }, false, ['verify']),
      Buffer.from(s, 'base64url'),
      new TextEncoder().encode(`${h}.${c}`),
    );
    expect(ok).toBe(true);
    expect(JSON.parse(Buffer.from(c, 'base64').toString()).iss).toBe(SERVICE_ACCOUNT.client_email);
  });
});

describe('ID token check (unchanged behaviour)', () => {
  it('a good token gives its uid, and keys are fetched once for two checks', async () => {
    await expect(auth.verifyFirebaseIdToken(idToken())).resolves.toBe('user-1');
    await expect(auth.verifyFirebaseIdToken(idToken({ sub: 'user-2' }))).resolves.toBe('user-2');
    expect(jwkFetches).toBe(1);
  });

  it.each([
    ['expired', () => idToken({ exp: Math.floor(nowMs / 1000) - 1 })],
    ['another project', () => idToken({ aud: 'other' })],
    ['wrong issuer', () => idToken({ iss: 'https://evil.example' })],
    ['issued in the future', () => idToken({ iat: Math.floor(nowMs / 1000) + 3600 })],
    ['no subject', () => idToken({ sub: '' })],
    ['signed by another key', () => idToken({}, generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey)],
    ['unknown key id', () => idToken({}, signer.privateKey, 'kid-x')],
    ['two parts', () => 'a.b'],
    ['not base64 json', () => 'x.y.z'],
    ['empty', () => ''],
    ['not a string', () => 7 as unknown as string],
  ])('refused: %s', async (_label, make) => {
    await expect(auth.verifyFirebaseIdToken(make())).rejects.toThrow();
  });

  it('no project id configured: refused', async () => {
    (globalThis as any).Deno = { env: { get: () => undefined } };
    auth.__resetAuthCacheForTests();
    await expect(auth.verifyFirebaseIdToken(idToken())).rejects.toThrow('project ID unavailable');
  });
});
