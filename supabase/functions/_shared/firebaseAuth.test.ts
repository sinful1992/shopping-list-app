/**
 * Fable audit (task 137): the same 79 auth lines were pasted into 4 edge
 * functions, and each request minted a new Google access token (one RSA sign
 * plus a round trip to Google) before its real work. Now there is one source
 * (_shared/firebaseAuth.ts) copied into each function by
 * scripts/sync-edge-auth.mjs, and the database token is reused until close
 * to expiry.
 */
import { readFileSync, existsSync } from 'fs';
import { join } from 'path';
import { generateKeyPairSync, webcrypto, createSign } from 'crypto';

const fnDir = join(__dirname, '..');
const FUNCTIONS = ['notify-receipt-scanned', 'notify-shopping-started', 'register-device-token', 'upsert-urgent-item'];
const shared = join(fnDir, '_shared', 'firebaseAuth.ts');

if (!(globalThis as any).crypto?.subtle) (globalThis as any).crypto = webcrypto;

describe('one auth source for the edge functions', () => {
  const want = existsSync(shared)
    ? '// GENERATED by scripts/sync-edge-auth.mjs from supabase/functions/_shared/firebaseAuth.ts.\n' +
      '// Do not edit here: edit the shared file and run the script.\n\n' +
      readFileSync(shared, 'utf8').replace(/\r\n/g, '\n')
    : null;

  it.each(FUNCTIONS)('%s has an up-to-date copy of the shared file', fn => {
    expect(want).not.toBeNull();
    const p = join(fnDir, fn, 'firebaseAuth.ts');
    expect(existsSync(p)).toBe(true);
    expect(readFileSync(p, 'utf8').replace(/\r\n/g, '\n')).toBe(want);
  });

  it.each(FUNCTIONS)('%s imports it and keeps no pasted auth code of its own', fn => {
    const src = readFileSync(join(fnDir, fn, 'index.ts'), 'utf8');
    expect(src).toContain("from './firebaseAuth.ts'");
    expect(src).not.toMatch(/function\s+(verifyFirebaseIdToken|assertGroupMember|_authDbToken|_authLoadKeys)\b/);
    expect(src).not.toMatch(/_auth[A-Z]/);
  });
});

