#!/usr/bin/env node
// Copies supabase/functions/_shared/firebaseAuth.ts into every edge function
// that verifies a Firebase user, as <function>/firebaseAuth.ts. The Supabase
// bundler is fed one function folder at a time, so each function imports its
// own copy ('./firebaseAuth.ts'); this keeps the copies identical.
//
//   node scripts/sync-edge-auth.mjs          write the copies
//   node scripts/sync-edge-auth.mjs --check  exit 1 if any copy differs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fnDir = join(root, 'supabase', 'functions');

export const EDGE_AUTH_FUNCTIONS = [
  'notify-receipt-scanned',
  'notify-shopping-started',
  'register-device-token',
  'upsert-urgent-item',
];

const BANNER =
  '// GENERATED by scripts/sync-edge-auth.mjs from supabase/functions/_shared/firebaseAuth.ts.\n' +
  '// Do not edit here: edit the shared file and run the script.\n\n';

export function expectedCopy() {
  return BANNER + readFileSync(join(fnDir, '_shared', 'firebaseAuth.ts'), 'utf8').replace(/\r\n/g, '\n');
}

export function copyPath(fn) {
  return join(fnDir, fn, 'firebaseAuth.ts');
}

function main() {
  const check = process.argv.includes('--check');
  const want = expectedCopy();
  const stale = [];
  for (const fn of EDGE_AUTH_FUNCTIONS) {
    const p = copyPath(fn);
    const have = existsSync(p) ? readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : null;
    if (have === want) continue;
    if (check) stale.push(fn);
    else writeFileSync(p, want);
  }
  if (check && stale.length) {
    console.error(`firebaseAuth.ts out of date in: ${stale.join(', ')}. Run node scripts/sync-edge-auth.mjs`);
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) main();
